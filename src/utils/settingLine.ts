/**
 * §7.2: ONE static asset, fetched the first time a connections door opens and
 * never with the chapter. It sits under `/bible/`, which vite.config.ts's
 * workbox `globIgnores` (`**\/bible/**\/*.json.gz`) keeps out of the PWA
 * precache — the same discipline the self-hosted Bible bundles follow, for the
 * same reason: most sessions never open a door.
 */
export const SETTING_LINES_URL = '/bible/connections/settings.json.gz'

/**
 * Fetch + parse the bundle. Deliberately a copy of the sniff in
 * src/utils/mapData.ts and src/bible/self-hosted.ts: Vite's dev server tags the
 * `.gz` `Content-Encoding: gzip` and the browser hands us plain JSON, while
 * Cloudflare Pages can hand back the raw gzip stream untouched. The magic
 * number (1f 8b) cannot collide with JSON's `{` (0x7b), so sniffing is correct
 * in both rather than green in dev and broken in production.
 */
async function fetchGzJson<T>(url: string, fetchImpl: typeof fetch): Promise<T | null> {
  const res = await fetchImpl(url)
  // Null rather than an error, all the way down: a missing bundle is a door
  // with no lines on it, which is a thing the reader is allowed to see. There
  // is no code for it in src/errors.ts and there should not be one — nothing
  // above here would do anything with it but swallow it.
  if (!res.ok) return null
  const bytes = new Uint8Array(await res.arrayBuffer())
  const isGzip = bytes[0] === 0x1f && bytes[1] === 0x8b
  const json = isGzip
    ? await new Response(
        new Response(bytes).body!.pipeThrough(new DecompressionStream('gzip'))
      ).text()
    : new TextDecoder().decode(bytes)
  return JSON.parse(json) as T
}

let filePromise: Promise<SettingLineFile | null> | null = null

/**
 * The file, once — memoized on the PROMISE so two doors opening at once share
 * one download. **Never throws**: a reader who is offline and has never fetched
 * it simply sees no setting lines, exactly as §7.3 says. A failed load is not
 * remembered, so the next door tries again.
 */
export function loadSettingLines(fetchImpl?: typeof fetch): Promise<SettingLineFile | null> {
  if (!filePromise) {
    filePromise = (async () => {
      const impl = fetchImpl ?? (typeof fetch === 'function' ? fetch : null)
      if (!impl) return null
      return await fetchGzJson<SettingLineFile>(SETTING_LINES_URL, impl)
    })().catch(() => {
      filePromise = null
      return null
    })
  }
  return filePromise
}

/** The line for one verse, or null where the file has nothing to say about it. */
export function settingLineIn(
  file: SettingLineFile | null,
  book: number,
  chapter: number,
  verse: number
): SettingLine | null {
  const found = file?.lines[settingLineKey(book, chapter, verse)]
  if (!found) return null
  return { text: found[0], source: found[1] }
}
